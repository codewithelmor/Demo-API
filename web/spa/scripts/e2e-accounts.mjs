// Shared helpers for the e2e account scripts (create-e2e-throwaway.mjs, provision-e2e-ci.mjs).
// Everything goes through the API, like a real user would (no database writes, no test-only endpoint).
// The dev stack uses a fake e-mail sender that logs the confirmation link; `docker compose logs api` shows it
// on a developer machine and on an Azure Pipelines agent alike. That log line holds a one-time token: these
// helpers never print it, and nothing here prints a password.
import { execFileSync } from 'node:child_process'
import { randomBytes, randomUUID } from 'node:crypto'

export const api = (process.env.E2E_API_URL ?? 'http://localhost:8080').replace(/\/+$/, '')
const headers = { 'content-type': 'application/json', 'X-CSRF': '1' }

export async function post(path, body, token) {
  const response = await fetch(`${api}${path}`, {
    method: 'POST',
    headers: token ? { ...headers, authorization: `Bearer ${token}` } : headers,
    body: JSON.stringify(body),
  })
  // Status only: a response body or request body could echo credentials.
  if (!response.ok) throw new Error(`${path} returned ${String(response.status)}`)
  return response.status === 204 ? undefined : await response.json().catch(() => undefined)
}

// 15+ characters (the API rule), random, letters and digits plus a fixed suffix with a space.
export const newPassword = () => `${randomBytes(12).toString('hex')} sample passphrase`

// Registers a new Customer and confirms the e-mail with the link from the API log. Returns { email, password }.
// Each account gets its own e-mail domain, so the masked address in the log line ("e***@<domain>") is unique
// and a link can never be taken from another account.
export async function createConfirmedCustomer(label, names = ['Sample', 'Person']) {
  const id = randomUUID().slice(0, 8)
  const email = `e2e.${label}.${id}@${id}.example.test`
  const password = newPassword()
  const startedAt = new Date().toISOString()
  await post('/api/v1/auth/register', {
    firstName: names[0],
    lastName: names[1],
    email,
    password,
  })

  const mask = `${email[0]}***@${email.split('@')[1]}`
  let link
  for (let attempt = 0; attempt < 40 && !link; attempt++) {
    const log = execFileSync(
      'docker',
      ['compose', 'logs', 'api', '--since', startedAt, '--no-log-prefix'],
      { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
    )
    link = log
      .split('\n')
      .reverse()
      .find((line) => line.includes('Confirm email for') && line.includes(mask))
      ?.match(/https?:\/\/\S+/)?.[0]
    if (!link) await new Promise((resolve) => setTimeout(resolve, 500))
  }
  if (!link)
    throw new Error(
      'No confirmation link in the API log. Is the stack running with the fake e-mail sender?',
    )

  const url = new URL(link)
  await post('/api/v1/auth/confirm-email', {
    userId: url.searchParams.get('userId'),
    token: url.searchParams.get('token'),
  })
  return { email, password }
}

// Signs in as the seed Admin. The password is generated by secrets-init and read from the api container.
export async function adminToken() {
  const email = process.env.E2E_ADMIN_EMAIL ?? process.env.SEED_ADMIN_EMAIL ?? 'admin@demoapi.local'
  const password =
    process.env.E2E_ADMIN_PASSWORD ??
    execFileSync(
      'docker',
      ['compose', 'exec', '-T', 'api', 'cat', '/run/secrets/dev/SeedAdmin__Password'],
      {
        encoding: 'utf8',
        env: { ...process.env, MSYS_NO_PATHCONV: '1' },
      },
    ).trim()
  const body = await post('/api/v1/auth/login', { email, password })
  if (typeof body?.accessToken !== 'string')
    throw new Error('Admin login returned no access token.')
  return body.accessToken
}

// Creates one product with plenty of stock, so the shared Customer can add it to a cart and order it.
export async function createStockedProduct(token) {
  const id = randomUUID().slice(0, 8)
  await post(
    '/api/v1/products',
    {
      name: `E2E product ${id}`,
      sku: `E2E-${id}`,
      description: 'Generated for the browser tests.',
      price: 9.99,
      stockQuantity: 1000,
    },
    token,
  )
}
